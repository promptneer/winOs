# -*- coding: utf-8 -*-
# 直接向 Bochs 窗口发送 WM_KEYDOWN / WM_KEYUP（绕过前台焦点捕获）
import ctypes, time, sys

u = ctypes.windll.user32
WM_KEYDOWN = 0x0100
WM_KEYUP = 0x0101

# VK / scan (set 1)
m = {'a': (0x41, 0x1E), 'b': (0x42, 0x30), 'c': (0x43, 0x2E),
     'd': (0x44, 0x20), 'e': (0x45, 0x12), 'f': (0x46, 0x21),
     'g': (0x47, 0x22), 'h': (0x48, 0x23), 'i': (0x49, 0x17),
     'j': (0x4A, 0x24), 'k': (0x4B, 0x25), 'l': (0x4C, 0x26),
     'm': (0x4D, 0x32), 'n': (0x4E, 0x31), 'o': (0x4F, 0x18),
     'p': (0x50, 0x19), 'q': (0x51, 0x10), 'r': (0x52, 0x13),
     's': (0x53, 0x1F), 't': (0x54, 0x14), 'u': (0x55, 0x16),
     'v': (0x56, 0x2F), 'w': (0x57, 0x11), 'x': (0x58, 0x2D),
     'y': (0x59, 0x15), 'z': (0x5A, 0x2C),
     '0': (0x30, 0x0B), '1': (0x31, 0x02), '2': (0x32, 0x03),
     '3': (0x33, 0x04), '4': (0x34, 0x05), '5': (0x35, 0x06),
     '6': (0x36, 0x07), '7': (0x37, 0x08), '8': (0x38, 0x09),
     '9': (0x39, 0x0A), ' ': (0x20, 0x39), '\n': (0x0D, 0x1C),
     '/': (0xBF, 0x35), '.': (0xBE, 0x34)}

def send_key(h, ch):
    vk, sc = m[ch]
    lparam_down = 1 | (sc << 16)
    lparam_up = 1 | (sc << 16) | 0xC0000000
    u.PostMessageW(h, WM_KEYDOWN, vk, lparam_down)
    time.sleep(0.05)
    u.PostMessageW(h, WM_KEYUP, vk, lparam_up)
    time.sleep(0.05)

if __name__ == '__main__':
    h = int(sys.argv[1])
    for ch in sys.argv[2]:
        send_key(h, ch)
    print('sent to', h, repr(sys.argv[2]))
